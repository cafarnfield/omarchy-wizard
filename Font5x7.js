// Space is narrow; every other glyph keeps the full 5-pixel cell.
function advance(ch) {
  return ch === " " ? 3 : W
}

function sanitize(text) {
  var out = ""
  var up = String(text || "").toUpperCase()
  for (var i = 0; i < up.length; i++) {
    var c = up.charAt(i)
    out += GLYPHS.hasOwnProperty(c) ? c : " "
  }
  return out
}

// Width in sprite pixels, including the 1-pixel gap between glyphs.
function measure(text) {
  var clean = sanitize(text)
  var w = 0
  for (var i = 0; i < clean.length; i++) w += advance(clean.charAt(i)) + 1
  return Math.max(0, w - 1)
}
